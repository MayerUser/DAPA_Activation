        device = torch.device("cuda")
        poly_gelu_gpu = poly_gelu.to(device)
        x_test_gpu = x_test.to(device)
        y_test_gpu = poly_gelu_gpu(x_test_gpu)
        
        print(f"Input tensor (GPU):  {x_test_gpu.cpu()}")
        print(f"Output tensor (GPU): {y_test_gpu.cpu()}")
